// Merges each subject's static, hand-authored question banks — subjects/<subject>/questions/<chapterId>.json
// (practice questions) and subjects/<subject>/questions-terms/<chapterId>.json (key-terms questions) —
// with chapter/module metadata into public/data/questions.json, shuffling each question's option order
// (so the correct answer's position carries no pattern) along the way.
//
// A subject's chapter list is either an explicit metadata list (FUNDAMENTALS) or derived automatically
// from the source folder (dp-700), where files named M1.1.md, M1.2.md ... all belong to the same Module 1.
//
// Nothing here calls an API or reads the book source beyond deriving module numbers — it's a deterministic
// merge, safe to rerun any time a file under questions/ or questions-terms/ changes.

