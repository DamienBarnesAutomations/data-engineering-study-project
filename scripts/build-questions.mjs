function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function extractQuestions(data) {
  if (Array.isArray(data)) return data;
  if (data && Array.isArray(data.questions)) return data.questions;
  throw new Error('Unexpected question file structure — expected an array or { questions: [...] }');
}

function finalizeQuestions(raw, chapterId) {
  return extractQuestions(raw).map((q) => {
    const order = shuffle([0, 1, 2, 3]);
    const options = order.map((i) => q.options[i]);
    const answer = order.indexOf(q.correctIndex);
    return { q: q.question, options, answer, explanation: q.explanation, chapterId };
  });
}

async function loadQuestions(dir, chapterId) {
  try {
    const raw = await readFile(path.join(dir, `${chapterId}.json`), 'utf-8');
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

async function loadTerms(dir, chapterId) {
  try {
    const raw = await readFile(path.join(dir, `${chapterId}.json`), 'utf-8');
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

// Derive module metadata from source filenames like M1.1.md, M1.2.md → Module 1.
async function deriveModules(subjectDir) {
  const sourceDir = path.join(subjectDir, 'source');
  const files = (await readdir(sourceDir)).filter((f) => /^M(\d+)\.\d+\.md$/i.test(f));
  const groups = new Map();
  for (const f of files) {
    const num = Number(f.match(/^M(\d+)\.\d+\.md$/i)[1]);
    if (!groups.has(num)) groups.set(num, []);
    groups.get(num).push(f);
  }
  return [...groups.keys()]
    .sort((a, b) => a - b)
    .map((num) => ({ id: `module-${num}`, kind: 'module', number: num, label: null, title: null }));
}

async function buildSubject(spec) {
  const subjectDir = path.join(root, 'subjects', spec.id);
  const questionsDir = path.join(subjectDir, 'questions');
  const termsDir = path.join(subjectDir, 'questions-terms');
  const chapterMeta = spec.derive ? await deriveModules(subjectDir) : spec.chapters;

  const available = new Set((await readdir(questionsDir)).map((f) => f.replace(/\.json$/, '')));

  const chapters = [];
  for (const meta of chapterMeta) {
    const raw = await loadQuestions(questionsDir, meta.id);
    if (!available.has(meta.id)) console.warn(`No question file for "${spec.id}/${meta.id}" — 0 questions.`);
    chapters.push({ ...meta, questions: finalizeQuestions(raw, meta.id) });
  }

  const terms = [];
  for (const meta of chapterMeta) {
    const raw = await loadTerms(termsDir, meta.id);
    if (raw) terms.push({ ...meta, questions: finalizeQuestions(raw, meta.id) });
  }

  return { id: spec.id, book: spec.book, chapters, terms };
}

async function main() {
  const subjects = [];
  for (const spec of SUBJECTS) subjects.push(await buildSubject(spec));

  const bank = { subjects };

  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, 'questions.json'), JSON.stringify(bank, null, 2), 'utf-8');

  console.log('Wrote public/data/questions.json');
  for (const s of subjects) {
    const total = s.chapters.reduce((n, c) => n + c.questions.length, 0);
    const totalTerms = s.terms.reduce((n, c) => n + c.questions.length, 0);
    console.log(`  ${s.id}: ${s.chapters.length} scopes, ${total} questions, ${totalTerms} terms`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});